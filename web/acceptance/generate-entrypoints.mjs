import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const [, , irPath, outputDirectory] = process.argv
if (!irPath || !outputDirectory || process.argv.length !== 4) {
  process.stderr.write(
    'usage: acceptance-entrypoint-generator <json-ir> <generated-test-output>\n',
  )
  process.exit(2)
}

try {
  const ir = JSON.parse(await readFile(irPath, 'utf8'))
  if (!ir.name || !Array.isArray(ir.scenarios)) {
    throw new Error('invalid acceptance IR')
  }

  const executions = ir.scenarios.flatMap((scenario, scenarioIndex) => {
    const examples = scenario.examples?.length ? scenario.examples : [{}]
    return examples.map((example, exampleIndex) => ({
      scenarioIndex,
      exampleIndex,
      name: `${scenario.name}/example_${exampleIndex + 1}`,
      example,
    }))
  })
  const generatedRelative =
    'e2e/generated/organization-registry.acceptance.spec.ts'
  const generatedPath = path.join(
    outputDirectory,
    'organization-registry.acceptance.spec.ts',
  )
  const source = `// Generated by acceptance/generate-entrypoints.mjs. Do not edit.\nimport { test } from '@playwright/test'\nimport { runAcceptanceScenario } from '../../acceptance/organization-registry.runtime'\n\nconst feature = ${JSON.stringify(ir, null, 2)} as const\n\ntest.describe(feature.name, () => {\n${executions
    .map(
      (execution) =>
        `  test(${JSON.stringify(execution.name)}, async ({ page, context }) => {\n    await runAcceptanceScenario(feature, ${execution.scenarioIndex}, ${JSON.stringify(execution.example)}, { page, context })\n  })`,
    )
    .join('\n\n')}\n})\n`

  await mkdir(outputDirectory, { recursive: true })
  await writeFile(generatedPath, source)
  const digest = createHash('sha256').update(source).digest('hex')
  const metadataDirectory = path.join(path.dirname(irPath), 'metadata')
  await mkdir(metadataDirectory, { recursive: true })
  await writeFile(
    path.join(metadataDirectory, 'features-organization-registry-feature.json'),
    `${JSON.stringify(
      {
        schema_version: 1,
        feature_path: 'acceptance/features/organization-registry.feature',
        ir_path: irPath,
        implementation_hash: `sha256:${digest}`,
        hash_scope: 'generated_files',
        generated_files: [generatedRelative],
      },
      null,
      2,
    )}\n`,
  )
} catch (error) {
  process.stderr.write(
    `${error instanceof Error ? error.message : String(error)}\n`,
  )
  process.exit(1)
}
